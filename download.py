"""Step 1: daily English-Wikipedia page views of 12 topics, 1 January 2016 to 30 September 2026.

    ./venv/bin/python download.py   -> data/<article>__<agent>.json (raw API answers), counts/daily_views.csv, results/pull.json

Source: the Wikimedia Pageviews REST API, https://wikimedia.org/api/rest_v1/metrics/pageviews/per-article/en.wikipedia/all-access/<agent>/<Article>/daily/20160101/20260930
(documentation: https://wikitech.wikimedia.org/wiki/Data_Platform/AQS/Pageviews). Licence: the pageview data is released under CC0 (https://dumps.wikimedia.org/other/pageviews/readme.html),
the API is free to use without a key, and Wikimedia's API etiquette asks for a descriptive User-Agent with contact information, which is sent, and for polite request rates: the
requests here are sequential with a one-second pause (39 requests in all). Cite: Wikimedia Foundation, Pageviews API (CC0).

Agents: "user" is what the analysis uses (traffic Wikimedia classifies as people's browsers); "automated" (traffic its classifier flags as bots posing as browsers; the class exists only
from 29 April 2020, see the audit) and "spider" (self-identified crawlers) are fetched for the 12 topics only to measure what the "user" filter removes. Three redirect titles are fetched with
agent "user" only, to show what a redirect title captures.

Committed: counts/daily_views.csv, a wide CSV of the daily counts (one column per article and agent, well under 5 MB, CC0 data). Not committed: data/ (the raw JSON answers, regenerated by this script;
results/pull.json has their checksums).
"""
import csv
import hashlib
import json
import ssl
import time
import urllib.parse
import urllib.request
from datetime import date, timedelta
from pathlib import Path

import certifi

HERE = Path(__file__).parent
UA = "research-portfolio (Rishit Raj Mathur; github.com/mrrishit909)"
START, END = "20160101", "20260930"
TOPICS = ["Easter", "Halloween", "Christmas", "Thanksgiving", "Influenza", "Measles", "Solar_eclipse_of_April_8,_2024", "FIFA_World_Cup",
          "Eurovision_Song_Contest", "Olympic_Games", "Japan", "Chicago"]
REDIRECTS = ["Olympics", "2024_solar_eclipse", "Flu"]
CTX = ssl.create_default_context(cafile=certifi.where())


def url_of(article, agent):
    return f"https://wikimedia.org/api/rest_v1/metrics/pageviews/per-article/en.wikipedia/all-access/{agent}/{urllib.parse.quote(article, safe=',')}/daily/{START}/{END}"


def fetch(article, agent):
    url = url_of(article, agent)
    for attempt in range(5):
        try:
            return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), context=CTX, timeout=60).read()
        except OSError:
            if attempt == 4: raise
            time.sleep(10 * (attempt + 1))


def main():
    (HERE / "data").mkdir(exist_ok=True); (HERE / "results").mkdir(exist_ok=True); (HERE / "counts").mkdir(exist_ok=True)
    jobs = [(a, "user") for a in TOPICS + REDIRECTS] + [(a, g) for g in ("automated", "spider") for a in TOPICS]
    info = {"pulled": date.today().isoformat(), "user_agent_sent": UA, "files": {}}; cols = {}
    for a, g in jobs:
        name = f"{a}__{g}.json"; f = HERE / "data" / name
        if f.exists(): raw = f.read_bytes()
        else:
            raw = fetch(a, g); f.write_bytes(raw); time.sleep(1)
        items = json.loads(raw)["items"]; cols[f"{a}|{g}"] = {it["timestamp"][:8]: it["views"] for it in items}
        info["files"][name] = {"url": url_of(a, g), "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest(), "days": len(items)}
    d0, d1 = date(2016, 1, 1), date(2026, 9, 30); days = [(d0 + timedelta(i)) for i in range((d1 - d0).days + 1)]
    with open(HERE / "counts" / "daily_views.csv", "w", newline="") as fh:
        w = csv.writer(fh); w.writerow(["date"] + list(cols))
        for d in days: k = d.strftime("%Y%m%d"); w.writerow([d.isoformat()] + [cols[c].get(k, "") for c in cols])
    (HERE / "results" / "pull.json").write_text(json.dumps(info, indent=2) + "\n")
    print(len(jobs), "files,", sum(v["bytes"] for v in info["files"].values()), "bytes of JSON")


if __name__ == "__main__":
    main()
